    fn clusters_keep_zwj_sequences_whole() {
        // ZWJ family stays whole.
        let family = "\u{1F468}\u{200D}\u{1F469}\u{200D}\u{1F466}";
        assert_eq!(emoji_cluster_len(family), Some(family.len()));

        // Trailing ZWJ with nothing after it ends the cluster.
        let dangling = "\u{1F468}\u{200D}";
        assert_eq!(emoji_cluster_len(dangling), Some("\u{1F468}".len()));
    }

    #[test]
    fn clusters_take_flags_as_a_pair() {
        let flag = "\u{1F1EC}\u{1F1E7}";
        assert_eq!(emoji_cluster_len(flag), Some(flag.len()));
    }

    #[test]
    fn ordinary_text_is_not_an_emoji_cluster() {
        assert_eq!(emoji_cluster_len("hello"), None);
        assert_eq!(emoji_cluster_len(""), None);
        // Nerd Font icons are private-use, not emoji.
        assert_eq!(emoji_cluster_len("\u{F048A}"), None);
    }

    #[test]
    fn names_are_sorted_for_binary_search() {
        // Unsorted data mis-resolves silently instead of failing.
        assert!(
            NAMES.windows(2).all(|w| w[0].0 < w[1].0),
            "NAMES must be sorted and free of duplicates"
        );
    }

    #[test]
    fn lookup_resolves_unicode_names() {
        assert_eq!(name_of("\u{1F600}"), "grinning face");
        assert_eq!(name_of("not-an-emoji"), "");
    }

    #[test]
    fn search_matches_names_not_just_glyphs() {
        // Regression: glyph-only search never matched words like "smile".
        let hits = search("smile");
        assert!(!hits.is_empty(), "\"smile\" must find something");
        assert!(
            hits.iter().all(|(_, e, _)| !name_of(e).is_empty()),
            "every hit should be a named emoji"
        );
        assert!(
            name_of(hits[0].1).contains("smil"),
            "best hit should actually be a smiling face, got {:?}",
            name_of(hits[0].1)
        );
    }

    #[test]
    fn search_ranks_whole_words_above_scattered_letters() {
        let hits = search("cat");
        let top = name_of(hits[0].1);
        assert!(
            top.split_whitespace().any(|w| w.starts_with("cat")),
            "expected a cat, got {top:?}"
        );
    }

    #[test]
    fn search_still_finds_a_pasted_emoji() {
        let hits = search("\u{1F600}");
        assert_eq!(hits[0].1, "\u{1F600}");
    }

