/// Byte length of the emoji cluster at the front of `s`, or `None` if `s`
/// does not start with one.
///
/// One emoji is often several codepoints (skin tone, variation selector,
/// keycap, ZWJ sequence, flag pair). Splitting per codepoint orphans the
/// modifiers, so keep the whole cluster together.
pub fn emoji_cluster_len(s: &str) -> Option<usize> {
    const ZWJ: char = '\u{200D}';
    const KEYCAP: char = '\u{20E3}';

    fn is_modifier(c: char) -> bool {
        matches!(c,
            // Fitzpatrick skin tones.
            '\u{1F3FB}'..='\u{1F3FF}'
            // Variation selectors: text vs emoji presentation.
            | '\u{FE0E}' | '\u{FE0F}'
            | KEYCAP
            // Tag characters, used by subdivision flags.
            | '\u{E0020}'..='\u{E007F}'
        )
    }

    fn is_regional(c: char) -> bool {
        matches!(c, '\u{1F1E6}'..='\u{1F1FF}')
    }

    /// Does this codepoint start an emoji?
    ///
    /// Ranges catch emoji newer than the dataset, else tofu via the text font.
    fn is_base(c: char) -> bool {
        if !name_of(&c.to_string()).is_empty() {
            return true;
        }
        matches!(c,
            '\u{1F300}'..='\u{1FAFF}'
            | '\u{1F000}'..='\u{1F02F}'
            | '\u{2600}'..='\u{27BF}'
            | '\u{2B00}'..='\u{2BFF}'
        )
    }

    let mut chars = s.char_indices();
    let (_, first) = chars.next()?;

    // Flags are exactly two regional indicators.
    if is_regional(first) {
        return match chars.next() {
            Some((i, second)) if is_regional(second) => Some(i + second.len_utf8()),
            _ => Some(first.len_utf8()),
        };
    }
    if !is_base(first) {
        return None;
    }

    let mut end = first.len_utf8();
    let rest = &s[end..];
    let mut it = rest.chars().peekable();
    while let Some(&c) = it.peek() {
        if is_modifier(c) {
            end += c.len_utf8();
            it.next();
            continue;
        }
        if c == ZWJ {
            // A ZWJ only joins when something follows it.
            let mut after = it.clone();
            after.next();
            match after.next() {
                Some(joined) if is_base(joined) || is_regional(joined) => {
                    end += c.len_utf8() + joined.len_utf8();
                    it.next();
                    it.next();
                    continue;
                }
                _ => break,
            }
        }
        break;
    }
    Some(end)
}

/// Unicode name for an emoji, or `""` if we have none.
pub fn name_of(emoji: &str) -> &'static str {
    match NAMES.binary_search_by(|(g, _)| (*g).cmp(emoji)) {
        Ok(i) => NAMES[i].1,
        Err(_) => "",
    }
}

/// Score `name` against `query`. Higher is better; `None` means no match.
///
/// Whole-word beats prefix beats substring beats subsequence.
fn score(name: &str, query: &str) -> Option<i32> {
    if name == query {
        return Some(1000);
    }
    if name.split_whitespace().any(|w| w == query) {
        return Some(800);
    }
    if name.split_whitespace().any(|w| w.starts_with(query)) {
        return Some(600);
    }
    if name.starts_with(query) {
        return Some(500);
    }
    if name.contains(query) {
        return Some(300);
    }
    // Loose subsequence fallback.
    let mut chars = name.chars();
    if query.chars().all(|q| chars.any(|c| c == q)) {
        // Shorter names win ties.
        return Some(100 - (name.len() as i32).min(90));
    }
    None
}
/// Flat search across all categories: `(category, emoji, supports_skin)`.
/// Matches on Unicode name and category, ranked best-first.
pub fn search(query: &str) -> Vec<(&'static str, &'static str, bool)> {
    let q = query.trim().to_lowercase();
    if q.is_empty() {
        let mut out = Vec::new();
        for cat in CATEGORIES {
            for (e, skin) in cat.emojis.iter() {
                out.push((cat.name, *e, *skin));
                if out.len() >= 200 {
                    return out;
                }
            }
        }
        return out;
    }
    let mut scored: Vec<(i32, &'static str, &'static str, bool)> = Vec::new();
    for cat in CATEGORIES {
        let cat_hit = cat.name.to_lowercase().contains(&q);
        for (e, skin) in cat.emojis.iter() {
            // Pasted emoji matches itself.
            let best = if *e == q {
                Some(1000)
            } else {
                score(name_of(e), &q).or(cat_hit.then_some(50))
            };
            if let Some(s) = best {
                scored.push((s, cat.name, *e, *skin));
            }
        }
    }
    scored.sort_by_key(|(s, ..)| std::cmp::Reverse(*s));
    scored.truncate(200);
    scored.into_iter().map(|(_, c, e, s)| (c, e, s)).collect()
}

